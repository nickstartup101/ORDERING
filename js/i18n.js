let currentLang = localStorage.getItem('ladolce_lang') || 'lo';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('ladolce_lang', lang);
  applyTranslations();
  if (typeof renderMenu === "function") renderMenu();
  if (typeof renderCartList === "function") renderCartList();
  if (typeof renderCustomerTicket === "function") renderCustomerTicket();
  if (typeof renderAnalytics === "function") renderAnalytics();
}

function t(key) {
  return (translations[currentLang] && translations[currentLang][key]) || translations['en'][key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });

  // Highlight Active Language Button
  ['lo', 'en', 'th'].forEach(l => {
    const btn = document.getElementById(`lang-btn-${l}`);
    if (btn) {
      if (l === currentLang) {
        btn.classList.add('text-primary', 'font-bold');
        btn.classList.remove('text-taupe');
      } else {
        btn.classList.remove('text-primary', 'font-bold');
        btn.classList.add('text-taupe');
      }
    }
  });
}
